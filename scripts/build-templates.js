'use strict';

// Inlines templates/*.html|txt into src/templates-data.js so the service never reads template
// files at runtime (Vercel's file tracing cannot see computed paths, which crashed the function).
// Run `npm run build:templates` after editing anything in templates/. A test fails if stale.

const fs = require('node:fs');
const path = require('node:path');

const NAMES = [
  'confirmation',
  'invite',
  'magic_link',
  'recovery',
  'email_change',
  'email_change_current',
  'reauthentication',
];

function build(dir) {
  const data = {};
  for (const name of NAMES) {
    data[name] = {
      html: fs.readFileSync(path.join(dir, `${name}.html`), 'utf8'),
      text: fs.readFileSync(path.join(dir, `${name}.txt`), 'utf8'),
    };
  }
  return (
    "'use strict';\n// GENERATED by scripts/build-templates.js - do not edit by hand.\n" +
    `module.exports = ${JSON.stringify(data, null, 2)};\n`
  );
}

if (require.main === module) {
  const out = path.join(__dirname, '..', 'src', 'templates-data.js');
  fs.writeFileSync(out, build(path.join(__dirname, '..', 'templates')));
  console.log('wrote', path.relative(process.cwd(), out));
}

module.exports = { build, NAMES };
